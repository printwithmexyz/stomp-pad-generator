"""Write a pad design as OpenSCAD source. All geometry is inline, so no SVG is imported."""

from shapely.geometry.polygon import orient

from .overlay import polygon_parts


def _number(value):
    return f'{value:.4f}'.rstrip('0').rstrip('.')


def _polygon_statement(polygon, indent='    '):
    polygon = orient(polygon)
    points, paths = [], []
    for ring in [polygon.exterior, *polygon.interiors]:
        corners = list(ring.coords)[:-1]
        paths.append(range(len(points), len(points) + len(corners)))
        points.extend(corners)
    point_list = ', '.join(f'[{_number(x)}, {_number(y)}]' for x, y in points)
    path_list = ', '.join('[' + ', '.join(str(i) for i in path) + ']' for path in paths)
    return f'{indent}polygon(points = [{point_list}], paths = [{path_list}]);'


def _module_2d(name, geometry):
    statements = [_polygon_statement(polygon) for polygon in polygon_parts(geometry)]
    return '\n'.join([f'module {name}() {{', *statements, '}'])


def _color_module(bodies):
    lines = ['module color_2d(body) {']
    for body in bodies:
        if body.is_base:
            continue
        lines.append(f'    if (body == {body.number}) {{')
        lines += [_polygon_statement(polygon, indent='        ') for polygon in polygon_parts(body.top)]
        lines.append('    }')
    return '\n'.join([*lines, '}'])


def _position_list(design):
    rows = [
        f'    [{x:.3f}, {y:.3f}, {rotation:.3f}, {number}],'
        for number, positions in design.positions_by_body().items()
        for x, y, rotation in positions
    ]
    return '\n'.join(['pyramid_positions = [', *rows, '];'])


def _body_legend(bodies):
    return '\n'.join(
        f'//   {body.number} = {body.fill}' + (' (base: the rest of the floor and the rim)' if body.is_base else '')
        for body in bodies
    )


def generate_openscad(design):
    """
    OpenSCAD source for the pad. Rendered as written it is the whole pad in
    one piece. Rendered with -D part=N it is body N alone, and the bodies fit
    together into the whole pad.
    """
    settings = design.settings
    color_bodies = [body.number for body in design.bodies if not body.is_base]
    return f"""// AUTO-GENERATED by the stomp pad generator.
// Geometry is inline and in millimetres. The artwork spans {design.width:.1f} x {design.height:.1f}.

// ===== PARAMETERS =====
// 0 renders the whole pad in one piece. A body number renders that filament's part alone:
{_body_legend(design.bodies)}
part = 0;

base_thickness = {_number(settings.base_thickness)};
outline_offset = {_number(settings.outline_offset)};
outline_height = {_number(settings.outline_height)};

pyramid_size = {_number(settings.packing.pyramid_size)};
pyramid_height = {_number(settings.pyramid_height)};
pyramid_style = {settings.packing.pyramid_style};

// Enclosed holes in the artwork. false cuts them through the pad.
// true leaves a floor recess_depth below the surface the pyramids stand on.
recess_voids = {'true' if design.voids_are_recessed else 'false'};
recess_depth = {_number(settings.recess_depth)};

// How far down from the floor surface each color other than the base reaches.
color_depth = {_number(design.color_depth)};
color_bodies = [{', '.join(str(number) for number in color_bodies)}];

total_height = base_thickness + outline_height;

// [x, y, rotation, body] of every pyramid, already checked to fit inside the artwork
{_position_list(design)}

// ===== SHAPES =====
{_module_2d('art_2d', design.art)}

{_module_2d('voids_2d', design.voids)}

{_color_module(design.bodies)}

module footprint_2d() {{
    offset(r = outline_offset, $fn = 48) {{
        art_2d();
        if (recess_voids) voids_2d();
    }}
}}

// Grown 0.01 so the recess overlaps the art cut instead of sharing a wall with it.
module recess_2d() {{
    offset(delta = 0.01) voids_2d();
}}

// The floor area a color body owns. Grown 0.001 so neighbouring colors overlap
// by a hair instead of leaving a sliver of base between them, then clipped so
// it never reaches into the rim or a recess.
module color_top_2d(body) {{
    difference() {{
        intersection() {{
            art_2d();
            offset(delta = 0.001) color_2d(body);
        }}
        if (recess_voids) recess_2d();
    }}
}}

module grip_pyramid(rotation) {{
    rotate([0, 0, 45 + rotation])
        cylinder(h = pyramid_height, r1 = pyramid_size / sqrt(2), r2 = 0, $fn = pyramid_style);
}}

// Sunk 0.01 so pyramid bases overlap the floor. Faces that only touch
// crash the CGAL kernel in some openscad-wasm builds.
module pyramids(body) {{
    for (position = pyramid_positions)
        if (body == 0 || position[3] == body)
            translate([position[0], position[1], base_thickness - 0.01])
                grip_pyramid(position[2]);
}}

// ===== ASSEMBLY =====
module pad_blank(without_color_tops) {{
    difference() {{
        linear_extrude(height = total_height) footprint_2d();
        translate([0, 0, base_thickness])
            linear_extrude(height = total_height) art_2d();
        if (recess_voids)
            translate([0, 0, base_thickness - recess_depth])
                linear_extrude(height = total_height) recess_2d();
        // Starts below the pad when colors run through the whole floor, so the
        // cut never ends flush with the underside.
        if (without_color_tops)
            translate([0, 0, color_depth < base_thickness ? base_thickness - color_depth : -1])
                linear_extrude(height = total_height + 1)
                    for (body = color_bodies) color_top_2d(body);
    }}
}}

module stomp_pad() {{
    pad_blank(without_color_tops = false);
    pyramids(0);
}}

module pad_body(body) {{
    if (body == 1) {{
        pad_blank(without_color_tops = true);
    }} else {{
        translate([0, 0, base_thickness - color_depth])
            linear_extrude(height = color_depth) color_top_2d(body);
    }}
    pyramids(body);
}}

if (part == 0) stomp_pad();
else pad_body(part);
"""
