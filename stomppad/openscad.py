"""Write a pad design as OpenSCAD source. All geometry is inline, so no SVG is imported."""

from .svg_parse import polygon_parts


def _number(value):
    return f'{value:.4f}'.rstrip('0').rstrip('.')


def _polygon_statement(polygon):
    points, paths = [], []
    for ring in [polygon.exterior, *polygon.interiors]:
        corners = list(ring.coords)[:-1]
        paths.append(range(len(points), len(points) + len(corners)))
        points.extend(corners)
    point_list = ', '.join(f'[{_number(x)}, {_number(y)}]' for x, y in points)
    path_list = ', '.join('[' + ', '.join(str(i) for i in path) + ']' for path in paths)
    return f'    polygon(points = [{point_list}], paths = [{path_list}]);'


def _module_2d(name, geometry):
    statements = [_polygon_statement(polygon) for polygon in polygon_parts(geometry)]
    return '\n'.join([f'module {name}() {{', *statements, '}'])


def _position_list(positions):
    rows = [f'    [{x:.3f}, {y:.3f}, {rotation:.3f}],' for x, y, rotation in positions]
    return '\n'.join(['pyramid_positions = [', *rows, '];'])


def generate_openscad(design):
    """OpenSCAD source for a single-body stomp pad."""
    settings = design.settings
    return f"""// AUTO-GENERATED by the stomp pad generator.
// Geometry is inline and in millimetres. The artwork spans {design.width:.1f} x {design.height:.1f}.

// ===== PARAMETERS =====
base_thickness = {_number(settings.base_thickness)};
outline_offset = {_number(settings.outline_offset)};
outline_height = {_number(settings.outline_height)};

pyramid_size = {_number(settings.packing.pyramid_size)};
pyramid_height = {_number(settings.pyramid_height)};
pyramid_style = {settings.pyramid_style};

// Enclosed holes in the artwork. false cuts them through the pad.
// true leaves a floor recess_depth below the surface the pyramids stand on.
recess_voids = {'true' if design.voids_are_recessed else 'false'};
recess_depth = {_number(settings.recess_depth)};

total_height = base_thickness + outline_height;

// [x, y, rotation] of every pyramid, already checked to fit inside the artwork
{_position_list(design.positions())}

// ===== SHAPES =====
{_module_2d('art_2d', design.art)}

{_module_2d('voids_2d', design.voids)}

module footprint_2d() {{
    offset(r = outline_offset, $fn = 48) {{
        art_2d();
        if (recess_voids) voids_2d();
    }}
}}

module grip_pyramid(rotation) {{
    rotate([0, 0, 45 + rotation])
        cylinder(h = pyramid_height, r1 = pyramid_size / sqrt(2), r2 = 0, $fn = pyramid_style);
}}

// ===== ASSEMBLY =====
module stomp_pad() {{
    difference() {{
        linear_extrude(height = total_height) footprint_2d();
        translate([0, 0, base_thickness])
            linear_extrude(height = total_height) art_2d();
        // Grown 0.01 so the recess overlaps the art cut instead of sharing a wall with it.
        if (recess_voids)
            translate([0, 0, base_thickness - recess_depth])
                linear_extrude(height = total_height) offset(delta = 0.01) voids_2d();
    }}
    // Sunk 0.01 so pyramid bases overlap the floor. Faces that only touch
    // crash the CGAL kernel in some openscad-wasm builds.
    for (position = pyramid_positions)
        translate([position[0], position[1], base_thickness - 0.01])
            grip_pyramid(position[2]);
}}

stomp_pad();
"""
