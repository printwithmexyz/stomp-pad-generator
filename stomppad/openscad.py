def _flip_y(coords, viewbox_height: float) -> str:
    """Format a ring as a SCAD ``points=[…]`` literal, Y-flipped to OpenSCAD's
    coordinate system (Y-up vs SVG's Y-down)."""
    return ", ".join(
        f"[{x:.3f}, {viewbox_height - y:.3f}]" for x, y in coords
    )


def _component_to_polygon_scad(component, viewbox_height: float, indent: str = "        ") -> str:
    """Render a :class:`Component` as a SCAD 2D shape (``polygon`` with
    ``difference()`` for holes). Self-contained — does not depend on the
    source SVG."""
    exterior = _flip_y(component.exterior, viewbox_height)
    if not component.holes:
        return f"{indent}polygon(points=[{exterior}]);"
    inner = "\n".join(
        f"{indent}    polygon(points=[{_flip_y(h, viewbox_height)}]);"
        for h in component.holes
    )
    return (
        f"{indent}difference() {{\n"
        f"{indent}    polygon(points=[{exterior}]);\n"
        f"{inner}\n"
        f"{indent}}}"
    )


def generate_body_scad(
    project: ShapeProject,
    body: Body,
    positions,
    *,
    params: Optional[dict] = None,
) -> str:
    """Self-contained SCAD that renders one body to a single STL.

    The body's geometry is **inlined** as ``polygon()`` calls rather than
    via ``import(svg_file) + resize()``, so the SCAD has no external file
    dependency and works on user-defined body groupings (which may merge
    disjoint shapes or include only a subset of the SVG's paths).

    ``positions`` are the packed pyramid positions for this body — usually
    obtained from :meth:`stomppad.cache.BodyOutputCache.positions_for`.
    ``params`` overlays the project's global_params on the default render
    params (``DEFAULT_RENDER_PARAMS``); per-body ``pyramid_overrides`` are
    expected to already be merged in by the caller.
    """
    if params is None:
        params = {}
    merged = {**DEFAULT_RENDER_PARAMS, **project.global_params, **params}
    base_thickness = merged["base_thickness"]
    outline_height = merged["outline_height"]
    pyramid_size = merged["pyramid_size"]
    pyramid_height = merged["pyramid_height"]
    pyramid_style = merged["pyramid_style"]

    viewbox_height = float(project.svg_info.get("viewbox_height") or 0)
    color = body.color_hex or "#cccccc"

    component_blocks = []
    for cid in body.component_ids:
        comp = project.component_or_none(cid)
        if comp is None:
            continue
        component_blocks.append(_component_to_polygon_scad(comp, viewbox_height))
    if not component_blocks:
        # Empty body — still emit a valid (zero-volume) SCAD so the caller
        # can decide whether to skip rendering.
        component_blocks.append("        // (no components)")

    has_rotation = bool(positions) and len(positions[0]) == 3
    position_lines = []
    for pos in positions:
        x = pos[0]
        y_flipped = viewbox_height - pos[1]
        if has_rotation:
            rot = pos[2]
            position_lines.append(f"    [{x:.3f}, {y_flipped:.3f}, {rot:.3f}],")
        else:
            position_lines.append(f"    [{x:.3f}, {y_flipped:.3f}],")
    positions_block = "\n".join(position_lines) if position_lines else "    // (no pyramids)"

    shape_block = "\n".join(component_blocks)
    pyramid_arg = (
        "grip_pyramid(path_rotation=pos[2])" if has_rotation else "grip_pyramid()"
    )

    return f"""// AUTO-GENERATED — body {body.id} ({body.name}), color={color}
// pattern={body.pattern}  •  components={body.component_ids}
// COORDINATE SYSTEM: SVG Y-down flipped to OpenSCAD Y-up via viewbox_height.

base_thickness = {base_thickness};
outline_height = {outline_height};
pyramid_size = {pyramid_size};
pyramid_height = {pyramid_height};
pyramid_style = {pyramid_style};
total_height = base_thickness + outline_height;

valid_pyramid_positions = [
{positions_block}
];

module body_shape_2d() {{
    union() {{
{shape_block}
    }}
}}

module grip_pyramid(path_rotation=0) {{
    // 45° diamond + path rotation; matches Python's pyramid footprint.
    rotate([0, 0, 45 + path_rotation]) {{
        cylinder(
            h = pyramid_height,
            r1 = pyramid_size / 1.414,
            r2 = 0,
            $fn = pyramid_style
        );
    }}
}}

module body_pyramids() {{
    for (pos = valid_pyramid_positions) {{
        // 0.01mm sink — same wasm-CGAL coplanar-face workaround documented
        // in the Phase 0 single-shape generator.
        translate([pos[0], pos[1], base_thickness - 0.01]) {{
            {pyramid_arg};
        }}
    }}
}}

module body_part() {{
    union() {{
        linear_extrude(height = total_height) body_shape_2d();
        body_pyramids();
    }}
}}

body_part();
"""


def generate_per_body_scads(project: ShapeProject, cache) -> dict[int, str]:
    """Return ``{body_id: scad_source}`` for every enabled body in the project.

    Skips disabled bodies. Empty bodies (no components) produce a SCAD that
    renders an empty solid — the caller can choose to skip the OpenSCAD
    invocation for those.
    """
    out: dict[int, str] = {}
    for body in project.bodies:
        if not body.enabled:
            continue
        positions = cache.positions_for(body.id)
        merged = _merged_pack_params(project, body)
        out[body.id] = generate_body_scad(
            project, body, positions, params=merged
        )
    return out
